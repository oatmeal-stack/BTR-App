import type { Book } from "../../src/domain/book";

export interface FactRow {
  id: string;
  year?: number;
  pages?: number;
}

const num = (s?: string) => {
  const n = Number((s ?? "").trim());
  return Number.isInteger(n) && n > 0 ? n : undefined;
};

const lines = (text: string) => text.split(/\r?\n/).filter((l) => l.trim() && !l.startsWith("#"));

/** data/facts.psv: id|pages|olYear (from Open Library). Only the page count is used directly. */
export function parsePages(text: string): FactRow[] {
  return lines(text)
    .map((l) => {
      const [id, pages] = l.split("|");
      return { id: id.trim(), pages: num(pages) };
    })
    .filter((r) => r.id && r.pages);
}

/** The Open Library years in data/facts.psv, which are never used on their own (see agreedYears). */
export function parseOlYears(text: string): Map<string, number> {
  const out = new Map<string, number>();
  for (const l of lines(text)) {
    const [id, , year] = l.split("|");
    const y = num(year);
    if (y) out.set(id.trim(), y);
  }
  return out;
}

/** How far apart two sources' years can be and still count as agreeing. */
export const YEAR_AGREEMENT = 2;

/**
 * A publication year is only believed when two independent sources agree on it: Wikidata's year is kept
 * when Open Library's year is within YEAR_AGREEMENT of it. Either source alone is wrong for roughly 1 book
 * in 5 to 15, and a confidently wrong year is worse than a blank. Wikidata's value is the one used.
 */
export function agreedYears(wikidata: FactRow[], olYears: Map<string, number>): FactRow[] {
  return wikidata.filter((r) => {
    const ol = olYears.get(r.id);
    return r.year !== undefined && r.year >= 1500 && ol !== undefined && Math.abs(r.year - ol) <= YEAR_AGREEMENT;
  });
}

/** data/years.psv: id|year (from Wikidata). */
export function parseYears(text: string): FactRow[] {
  return lines(text)
    .map((l) => {
      const [id, year] = l.split("|");
      return { id: id.trim(), year: num(year) };
    })
    .filter((r) => r.id && r.year);
}

/**
 * Puts the looked-up year and page count on each book, only where there is a blank. A year from one of
 * your own lists is never replaced, and a value typed in Edit is never touched (this only runs on the seed).
 */
export function applyFacts(books: Book[], rows: FactRow[]): void {
  const byId = new Map<string, FactRow>();
  for (const r of rows) byId.set(r.id, { ...byId.get(r.id), ...r });
  for (const b of books) {
    const f = byId.get(b.id);
    if (!f) continue;
    if (b.year === undefined && f.year) b.year = f.year;
    if (b.pageCount === undefined && f.pages) b.pageCount = f.pages;
  }
}

/**
 * Everything looked up, applied the way the build does it: a Wikidata year only when Open Library agrees
 * (agreedYears), page counts from Open Library, and only into blanks. `yearsText` is data/years.psv and
 * `factsText` is data/facts.psv.
 */
export function applyLookups(books: Book[], yearsText: string, factsText: string): void {
  const years = agreedYears(parseYears(yearsText), parseOlYears(factsText));
  applyFacts(books, [...years, ...parsePages(factsText)]);
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

/**
 * Fills the year and page count on a library that is already live. Only blanks are filled, so a value
 * you typed in Edit is never overwritten, and it is safe to run again.
 */
export function toFactsSql(books: Book[]): string {
  const rows = books
    .filter((b) => b.year || b.pageCount)
    .map((b) => ` (${q(b.id)},${b.year ?? "null"},${b.pageCount ?? "null"})`);
  return [
    "-- Generated by scripts/build-seed.ts. Only fills blank years and page counts; safe to re-run.",
    "update books set year = coalesce(books.year, v.year), page_count = coalesce(books.page_count, v.pages), updated_at = now()",
    "from (values",
    rows.join(",\n"),
    ") as v(id, year, pages)",
    "where books.id = v.id and (books.year is null or books.page_count is null);",
    "",
  ].join("\n");
}
